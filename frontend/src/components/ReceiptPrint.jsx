import { money, shortDate } from './UI';

export default function ReceiptPrint({ order, onClose }) {
  if (!order) return null;
  const handlePrint = () => window.print();
  return <div className="modal-backdrop" role="presentation" onMouseDown={(e) => e.target === e.currentTarget && onClose()}>
    <div className="receipt-modal"><div className="receipt-actions no-print"><button type="button" className="modal-close" onClick={onClose}>Close</button></div>
      <div className="print-document" id="waygo-receipt">
        <div className="receipt-brand"><div><strong>UniRide</strong><span>RIDER RECEIPT</span></div></div>
        <div className="receipt-status">PAYMENT SUMMARY · {String(order.status || '').toUpperCase()}</div>
        <h2>Order receipt</h2><p className="receipt-subtitle">Thank you for choosing UniRide.</p>
        <div className="receipt-code-row"><span>Receipt number</span><strong>{order.receiptNumber || `WG-${String(order._id).slice(-8).toUpperCase()}`}</strong></div>
        <div className="receipt-code-row"><span>Order date</span><strong>{shortDate(order.createdAt)}</strong></div>
        <div className="receipt-code-row"><span>Order type</span><strong>{order.orderType === 'food' ? 'Food delivery' : 'Product delivery'}</strong></div>
        <div className="receipt-section"><h3>MERCHANT</h3><strong>{order.shop}</strong><p>{order.meal ? `${order.meal} order` : 'Online order'}</p></div>
        <div className="receipt-section"><h3>ITEMS</h3>{order.items?.map((item, i) => <div className="receipt-item" key={`${item.itemId}-${i}`}><span>{item.name} × {item.quantity}</span><strong>{money(item.price * item.quantity)}</strong></div>)}</div>
        <div className="receipt-section"><h3>DELIVERY ADDRESS</h3><p>{order.deliveryAddress}</p></div>
        <div className="receipt-totals"><div><span>Subtotal</span><strong>{money(order.subtotal)}</strong></div><div><span>Delivery fee</span><strong>{money(order.deliveryFee)}</strong></div><div className="receipt-total"><span>Total paid</span><strong>{money(order.total)}</strong></div></div>
        <div className="receipt-footer">Generated by UniRide · Keep this receipt for your records.</div>
      </div>
      <div className="receipt-bottom-actions no-print"><button type="button" className="button button-primary" onClick={handlePrint}>Print receipt</button><button type="button" className="button button-secondary" onClick={onClose}>Close</button></div>
    </div>
  </div>;
}
